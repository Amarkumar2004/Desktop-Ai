async function runLiveTests() {
  console.log('====================================================');
  console.log('🚀 1. TESTING DIRECT LOCAL OLLAMA INFERENCE (llama3.2:1b)');
  console.log('====================================================');
  try {
    const oRes = await fetch('http://127.0.0.1:11434/api/generate', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        model: 'llama3.2:1b',
        prompt: 'Give a 1-sentence tip on how to optimize React re-renders.',
        stream: false,
      }),
    });
    const oData = await oRes.json();
    console.log('🧠 Ollama Neural Reply:', oData.response.trim());
  } catch (err) {
    console.error('Ollama Direct Test Error:', err);
  }

  console.log('\n====================================================');
  console.log('🎙️ 2. TESTING VOICE ASSISTANT PIPELINE (/api/voice/process)');
  console.log('====================================================');
  try {
    const vRes = await fetch('http://localhost:3000/api/voice/process', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        prompt: 'Create task Integrate Supabase Auth and WebSockets',
      }),
    });
    const vData = await vRes.json();
    console.log('Voice Response Status:', vData.success ? '✅ SUCCESS' : '❌ FAILED');
    console.log('Mode Used:', vData.modeUsed);
    console.log('Assigned Agent:', vData.assignedAgent);
    console.log('Spoken Reply Text:', vData.replyText);
    console.log('Action Generated:', JSON.stringify(vData.action));
  } catch (err) {
    console.error('Voice Route Error:', err);
  }

  console.log('\n====================================================');
  console.log('📁 3. TESTING LOCAL PC WORKSPACE ACTION (/api/local/action)');
  console.log('====================================================');
  try {
    const aRes = await fetch('http://localhost:3000/api/local/action', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        actionType: 'CREATE_FILE',
        payload: {
          filename: 'voice-orchestrator.ts',
          content: '// Auto-generated by Local Voice AI Engine\nexport const engine = "Ollama-llama3.2";\n',
        },
      }),
    });
    const aData = await aRes.json();
    console.log('Action Status:', aData.success ? '✅ SUCCESS' : '❌ FAILED');
    console.log('Message:', aData.message);
    console.log('File Created At:', aData.filePath);
  } catch (err) {
    console.error('Action Route Error:', err);
  }
}

runLiveTests();
